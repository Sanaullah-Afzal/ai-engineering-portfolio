    for entry in st.session_state.ui_messages:
        with st.chat_message(entry["role"], avatar="👤" if entry["role"] == "user" else "🤖"):
            if "traces" in entry:
                for trace in entry["traces"]:
                    # 2 different types of traces, one is tool input and other is tool output, so we are checking the type of trace and then displaying it accordingly
                    if trace["type"] == "tool_input": #input will have json format
                        st.markdown(f"**⚡ Intent Recognized:** `{trace['name']}`") # if recognized then whats the intent ot the tool name 
                        with st.expander(f"📥 View Generated Input ({trace['name']})", expanded=False): # with the help of expader, we see the tool output
                            st.json(trace["args"]) # what arg agent has used to call the particular tool, we can see it in json format
                    elif trace["type"] == "tool_output": #output of the tool
                        with st.expander(f"📤 View Raw Output ({trace['name']})", expanded=False):
                            st.code(trace["content"], language="text")
            st.markdown(entry["content"]) # actual content from the model
    
    # this part is responsible for chatting,first chat input
    if user_input := st.chat_input("Query fleet telemetry, corridor updates, or compliance thresholds..."):
        
        st.session_state.ui_messages.append({"role": "user", "content": user_input})
        with st.chat_message("user", avatar="👤"):
            st.markdown(user_input)

        with st.chat_message("assistant", avatar="🤖"): # assistant uses the fde agent  
            final_response = ""
            current_traces = [] 
            # this will go to fde_agent
            with st.status("🧠 Initializing Core Reasoner Node...", expanded=True) as status:
                events = fde_agent.stream(
                    {"messages": [HumanMessage(content=user_input)]}, 
                    config=thread_config,
                    stream_mode="updates"
                )
                # event is multiple thing , what node etc it has changed
                for event in events:
                    for node_name, node_state in event.items():
                        
                        if node_name == "reasoner": # it can use multiple tools or else it can be a final response
                            latest_msg = node_state["messages"][-1]
                            
                            # A. Intercept Tool Call Requests (Inputs)
                            if hasattr(latest_msg, "tool_calls") and latest_msg.tool_calls:
                                status.update(label="🧠 Agent generated tool parameters...")
                                for tool_call in latest_msg.tool_calls:
                                    st.markdown(f"**⚡ Intent Recognized:** `{tool_call['name']}`")
                                    with st.expander(f"📥 View Generated Input ({tool_call['name']})", expanded=False):
                                        st.json(tool_call['args'])
                                    
                                    current_traces.append({ # appendign to the current traces, so that we can see the traces in the chat    
                                        "type": "tool_input",
                                        "name": tool_call['name'],
                                        "args": tool_call['args']
                                    })
                                    # writing same thing in audit log
                                    write_audit_log(
                                        session_id=st.session_state.thread_id,
                                        node_name="reasoner",
                                        tool_name=tool_call['name'],
                                        content=json.dumps(tool_call['args'])
                                    )
                            
                            # B. Intercept Final Generation
                            # if it contains the tool call then it will not be a final response
                            if latest_msg.content:
                                final_response = latest_msg.content
                                status.update(label="📝 Generating Operational Resolution Report...")
                                
                                write_audit_log(
                                    session_id=st.session_state.thread_id,
                                    node_name="reasoner_final",
                                    tool_name="LLM Text Synthesis",
                                    content=final_response
                                )
                                
                        elif node_name == "tools": # not coming from resasoner, its directly coming from the tools, so we will see the output of the tools
                            status.update(label="🔧 Executing Enterprise Subsystem Tools...")
                            for msg in node_state.get("messages", []):
                                if isinstance(msg, ToolMessage):
                                    with st.expander(f"📤 View Raw Output ({msg.name})", expanded=False):
                                        st.code(msg.content, language="text")
                                        
                                    current_traces.append({
                                        "type": "tool_output",
                                        "name": msg.name,
                                        "content": msg.content
                                    })
                                    
                                    write_audit_log(
                                        session_id=st.session_state.thread_id,
                                        node_name="tools",
                                        tool_name=msg.name,
                                        content=msg.content
                                    )
                # complete means one turn is complete, when whole reasining of chat is completed
                status.update(label="Incident Matrix Evaluation Complete", state="complete", expanded=False)
                
            if final_response: # if final response is there, then we will say role of assistant
                st.markdown(final_response)
                st.session_state.ui_messages.append({ # appending the final response to the session state, so that we can see the previous messages in the chat
                    "role": "assistant",
                    "content": final_response,
                    "traces": current_traces
                })
            else:
                error_fallback = "⚠️ Execution Timeout: System engine encountered an unresolved processing edge case."
                st.error(error_fallback)

